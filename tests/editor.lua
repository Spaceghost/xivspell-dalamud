package.path = 'lua/?.lua;' .. package.path
local E = require('xivspell.editor')
assert(E.parse(':e ruin').op == 'edit')
assert(E.parse(':edit radiant aegis').argument == 'radiant aegis')
assert(E.parse(':nvim radiant aegis').op == 'neovim')
assert(E.parse(':w').op == 'write')
assert(E.parse(':wq').op == 'writequit')
assert(E.parse(':q').op == 'quit')
assert(E.parse(':reload').op == 'reload')
assert(not E.parse(':!rm -rf anything'))
assert(not E.parse(':lua os.execute("bad")'))
assert(not E.parse(':w arbitrary.lua'))
assert(not E.parse('ruin'))
print('PASS editor command aliases and rejection of shell, arbitrary Lua and foreign file writes')
